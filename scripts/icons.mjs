#!/usr/bin/env node
// B-14: the sixteen icons of the Icons page, as Kotlin, and the kit's own after them (B-195).
//
//   node scripts/icons.mjs [--check]
//
// The page keeps each icon as one SVG path on a 24 grid (`static ICONS` of «Иконки и заготовки»), drawn with
// stroke 2, square caps and no fill. This reads that array out of the vendored page — the page's own array
// literal, evaluated alone — and writes it as path data the kit turns into ImageVectors. Icons are never
// generated or damaged at run time: the one accent each carries is already in its path. --check writes
// nothing and fails when the committed file is not what the page says today.
//
// Since the code is primary (research D20), the kit may add an icon the page does not draw. KIT lists each one with
// the item that added it, after the page's sixteen; the check fails when the page itself comes to draw one of them
// (by name or by path), as a known entry that no longer differs is one nobody reads.

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import vm from 'node:vm';

const ROOT = resolve(import.meta.dirname, '..');
const PAGE = join(ROOT, 'reference/design-system/mutant-ui Иконки и заготовки.dc.html');
const OUT = join(ROOT, 'mutant-core/src/commonMain/kotlin/io/github/youndie/mutant/icons/MutantIconPaths.kt');

const html = readFileSync(PAGE, 'utf8');
const m = html.match(/static ICONS = (\[[\s\S]*?\n {2}\]);/);
if (!m) throw new Error('static ICONS not found on the Icons page');
const ICONS = vm.runInNewContext(m[1]);

// The page names the icons in Russian; the kit's names are the Material icons each is redrawn from.
const NAMES = {
  'меню': 'Menu', 'назад': 'Back', 'закрыть': 'Close', 'поиск': 'Search', 'домой': 'Home', 'добавить': 'Add',
  'удалить': 'Delete', 'править': 'Edit', 'поделиться': 'Share', 'обновить': 'Refresh', 'настройки': 'Settings',
  'готово': 'Done', 'ошибка': 'Error', 'внимание': 'Warning', 'инфо': 'Info', 'время': 'Schedule',
};
const missing = ICONS.filter(([n]) => !NAMES[n]).map(([n]) => n);
const stale = Object.keys(NAMES).filter((n) => !ICONS.some(([x]) => x === n));
if (ICONS.length !== 16 || missing.length || stale.length) {
  throw new Error(`the page's icons changed: ${ICONS.length} icons, unnamed ${missing}, gone ${stale}`);
}

// The kit's own icons: [kit name, path on the 24 grid, why, the item].
const KIT = [
  // The designer's answer 20 to B-168: the demo's Recording draws this triangle three times (`Слушать`, the tracks)
  // and the page none. The same stroke, caps and grid as the page's, with no accent of damage.
  ['Play', 'M8 5l11 7-11 7z', 'the designer\'s answer 20 to B-168, no accent of damage', 'B-195'],
];
const drawn = KIT.filter(([name, d]) => ICONS.some(([ru, x]) => x === d || NAMES[ru] === name)).map(([name]) => name);
if (drawn.length) throw new Error(`the page now draws the kit's ${drawn}; take it from the page and drop it from KIT`);

const L = [];
L.push('// GENERATED by scripts/icons.mjs from `static ICONS` of reference/design-system/mutant-ui Иконки и заготовки.dc.html');
L.push('// and the kit\'s own icons in the script\'s KIT.');
L.push('// Do not edit.');
L.push('@file:Suppress("ktlint")');
L.push('');
L.push('package io.github.youndie.mutant.icons');
L.push('');
L.push('/** Each icon as the page draws it, the kit\'s own as the page would: one path on a 24 grid, stroke 2, square caps, no fill. */');
L.push('internal object MutantIconPaths {');
for (const [ru, d, accent] of ICONS) {
  L.push(`    /** «${ru}»: ${accent}. */`);
  L.push(`    const val ${NAMES[ru].toUpperCase()}: String = ${JSON.stringify(d)}`);
}
for (const [name, d, why, item] of KIT) {
  L.push(`    /** ${item}, the kit's own: ${why}. */`);
  L.push(`    const val ${name.toUpperCase()}: String = ${JSON.stringify(d)}`);
}
L.push('');
L.push('    /** The icons in the page\'s order, then the kit\'s own, by their kit names. */');
L.push('    val all: List<Pair<String, String>> =');
L.push('        listOf(');
for (const [ru] of ICONS) L.push(`            "${NAMES[ru]}" to ${NAMES[ru].toUpperCase()},`);
for (const [name] of KIT) L.push(`            "${name}" to ${name.toUpperCase()},`);
L.push('        )');
L.push('');
L.push('    /** The kit\'s own icons, which the page does not draw, each with the item that added it (research D20). */');
L.push('    val kit: Map<String, String> =');
L.push('        mapOf(');
for (const [name, , , item] of KIT) L.push(`            "${name}" to "${item}",`);
L.push('        )');
L.push('}');
L.push('');
const text = L.join('\n');

if (process.argv.includes('--check')) {
  let now = '';
  try { now = readFileSync(OUT, 'utf8'); } catch {}
  if (now !== text) { console.error(`${OUT} is not what the Icons page and KIT say; run node scripts/icons.mjs`); process.exit(1); }
  console.log(`icons: ${ICONS.length} icons match the Icons page; the kit's own: ${KIT.map(([n, , , i]) => `${n} (${i})`).join(', ')}`);
} else {
  writeFileSync(OUT, text);
  console.log(`icons: ${ICONS.length} icons of the page and ${KIT.length} of the kit written`);
}
