#!/usr/bin/env node
// B-08: generate the kit's tokens (research D8).
//
//   node scripts/tokens.mjs [--check]
//
// Two sources, both vendored and both read here, never retyped:
// - reference/design-system/mutant-tokens.json: the two themes' colours, type, grid, genome, motion;
// - reference/design-system/mutant-generator.js, run in Node: its `static K` (the type profiles the engine
//   actually draws with) and the colours of `static TH` the tokens do not carry (the divider's comets, the
//   cocoon's two paints, the disabled tint and darkening, the print flag).
// Where both say something, they must agree, or the check fails; the one known disagreement is listed in
// KNOWN with its cause, and the engine's value is generated (research D4).
//
// Writes one committed Kotlin file in the layout ktlint keeps. --check writes nothing and fails when the
// file is stale or the sources disagree unexpectedly. 1 CSS px = 1 dp; a font size in px is that many sp.

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import vm from 'node:vm';

const ROOT = resolve(import.meta.dirname, '..');
const DESIGN = join(ROOT, 'reference/design-system');
const OUT = join(ROOT, 'mutant-core/src/commonMain/kotlin/io/github/youndie/mutant/tokens/MutantTokens.kt');
const T = JSON.parse(readFileSync(join(DESIGN, 'mutant-tokens.json'), 'utf8')).mutant;
const ctx = { window: {}, Math, Float32Array, Int32Array, NaN, console };
vm.createContext(ctx);
vm.runInContext(readFileSync(join(DESIGN, 'mutant-generator.js'), 'utf8'), ctx);
const G = ctx.window.MutantGenerator;

// The engine's colour names against the tokens' (where the tokens carry them).
const TH_TO_TOKEN = {
  ink: 'ink', green: 'primary', mag: 'magenta', cyan: 'cyan', red: 'danger', white: 'phosphor', bg: 'background',
  surf: 'surface', surf2: 'surface-variant', blue: 'no-signal', amber: 'amber', acc: 'text-accent', mis: 'misregister',
  deep: 'shadow-deep', focus: 'focus', hlDark: 'highlight-on-dark', drop: 'dropout',
};
// The engine's colours the tokens do not carry, generated from TH.
const ENGINE_ONLY = { comet: 'comet', coc1: 'cocoon1', coc2: 'cocoon2' };
// Where the tokens and the engine disagree on purpose, and why.
const KNOWN = new Map([
  ['profile pill round', 'tokens say radius "full"; static K gives the pill r 99 with no round flag, so its corners are randomised and clamped to half the side'],
]);

const problems = [];
const seen = new Set();
const disagree = (what, detail) => { seen.add(what); if (!KNOWN.has(what)) problems.push(`${what}: ${detail}`); };
for (const th of ['efir', 'kopiya']) {
  for (const [k, v] of Object.entries(G.TH[th])) {
    const t = TH_TO_TOKEN[k];
    if (t && T.color[th][t] !== v) disagree(`colour ${th} ${k}`, `TH ${v}, tokens ${t} ${T.color[th][t]}`);
    if (!t && typeof v === 'string' && !ENGINE_ONLY[k]) disagree(`colour ${th} ${k}`, 'an engine colour this script does not know');
  }
}
const PROFILES = Object.keys(T.profile);
for (const k of PROFILES) {
  const p = T.profile[k], K = G.K[k], full = p.radius === 'full';
  const want = { r: full ? 99 : p.radius, over: p.overhang, cf: p['drip-share'], fill: p.fill, ow: p.outline, marks: p.marks, edge: p.mosaic, wob: p.wobble, dead: p['dead-pixels'], round: full ? 1 : 0 };
  const got = { r: K.r, over: K.over, cf: K.cf, fill: K.fill, ow: K.ow ?? 3, marks: K.marks ?? 1, edge: K.edge ?? 1, wob: K.wob ?? 1, dead: K.dead ?? 0, round: K.round ?? 0 };
  for (const f of Object.keys(want)) if (want[f] !== got[f]) disagree(`profile ${k} ${f}`, `tokens ${want[f]}, K ${got[f]}`);
}
if (Object.keys(G.K).sort().join() !== PROFILES.slice().sort().join()) problems.push(`profiles: tokens ${PROFILES} against K ${Object.keys(G.K)}`);
for (const k of KNOWN.keys()) if (!seen.has(k)) problems.push(`${k}: listed as known, but the sources now agree`);

// ---- Kotlin -----------------------------------------------------------------------------------------
const camel = (s) => s.replace(/[-/](.)/g, (_, c) => c.toUpperCase());
const pascal = (s) => camel(s).replace(/^./, (c) => c.toUpperCase());
const constName = (s) => camel(s).replace(/([A-Z])/g, '_$1').toUpperCase();
const color = (hex) => `Color(0xFF${hex.slice(1).toUpperCase()})`;
const dbl = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const rgb = (a) => `Color(0xFF${a.map((x) => x.toString(16).padStart(2, '0')).join('').toUpperCase()})`;
const COLORS = Object.keys(T.color.efir);
const FILL = { green: 'Primary', surf: 'Surface', surf2: 'SurfaceVariant', white: 'Phosphor', mag: 'Magenta' };

const L = [];
L.push('// GENERATED by scripts/tokens.mjs from reference/design-system/mutant-tokens.json and the engine colours and');
L.push(`// type profiles of reference/design-system/mutant-generator.js. Do not edit. Tokens: «${T.version}».`);
L.push('');
L.push('package io.github.youndie.mutant.tokens');
L.push('');
L.push('import androidx.compose.runtime.Immutable');
L.push('import androidx.compose.ui.graphics.Color');
L.push('');
L.push('/**');
L.push(' * The colours of one theme (`mutant/color`), and the engine\'s own the tokens do not carry: [comet] (the');
L.push(' * divider\'s strokes), [cocoon1] and [cocoon2] (the skeleton\'s paints), the disabled body\'s [disabledTint]');
L.push(' * and [disabledDarken], and [print] — «Копия» shows print defects where «Эфир» shows VHS.');
L.push(' */');
L.push('@Immutable');
L.push('public class MutantColors internal constructor(');
for (const k of COLORS) L.push(`    public val ${camel(k)}: Color,`);
for (const n of Object.values(ENGINE_ONLY)) L.push(`    public val ${n}: Color,`);
L.push('    public val disabledTint: Color,');
L.push('    public val disabledDarken: Float,');
L.push('    public val print: Boolean,');
L.push(')');
L.push('');
L.push('/** The two themes: «Эфир», dark, and «Копия», light. */');
L.push('public object MutantPalettes {');
for (const [th, name, title] of [['efir', 'Efir', 'Эфир'], ['kopiya', 'Kopiya', 'Копия']]) {
  const c = T.color[th], g = G.TH[th];
  L.push(`    /** «${title}». */`);
  L.push(`    public val ${name}: MutantColors =`);
  L.push('        MutantColors(');
  for (const k of COLORS) L.push(`            ${camel(k)} = ${color(c[k])},`);
  for (const [k, n] of Object.entries(ENGINE_ONLY)) L.push(`            ${n} = ${color(g[k])},`);
  L.push(`            disabledTint = ${rgb(g.disT)},`);
  L.push(`            disabledDarken = ${dbl(g.disK)}f,`);
  L.push(`            print = ${g.print ? 'true' : 'false'},`);
  L.push('        )');
  L.push('');
}
L.pop();
L.push('}');
L.push('');

// type
L.push('/** Type roles (`mutant/type`): sizes in sp, weights, letter spacing in sp. */');
L.push('internal object MutantType {');
for (const [role, v] of Object.entries(T.type)) {
  L.push(`    /** \`${role}\`: ${v.family} (${v.license}). */`);
  L.push(`    val ${pascal(role)}Sizes: List<Int> = listOf(${v.sizes.join(', ')})`);
  if (v.weights) L.push(`    val ${pascal(role)}Weights: List<Int> = listOf(${v.weights.join(', ')})`);
  if (v['letter-spacing'] !== undefined) L.push(`    const val ${constName(role)}_LETTER_SPACING: Double = ${dbl(v['letter-spacing'])}`);
  L.push('');
}
L.pop();
L.push('}');
L.push('');

// grid
const g = T.grid;
L.push('/** The grid and limits (`mutant/grid`), dp. */');
L.push('internal object MutantGrid {');
L.push(`    const val UNIT: Double = ${dbl(g.unit)}`);
L.push(`    const val TOUCH_TARGET: Double = ${dbl(g['touch-target'])}`);
L.push(`    const val SCREEN_MARGIN: Double = ${dbl(g['screen-margin'])}`);
L.push(`    val MosaicBlocks: List<Int> = listOf(${g['mosaic-blocks'].join(', ')})`);
L.push(`    const val CLEAN_ZONE_HORIZONTAL: Double = ${dbl(g['clean-zone-padding'].horizontal)}`);
L.push(`    const val CLEAN_ZONE_VERTICAL: Double = ${dbl(g['clean-zone-padding'].vertical)}`);
L.push(`    const val CLEAN_ZONE_MOSAIC_EXTRA: Double = ${dbl(g['clean-zone-padding']['mosaic-extra'])}`);
L.push(`    const val OVERHANG_MAX: Double = ${dbl(g['overhang-max'])}`);
L.push(`    const val OVERHANG_LIST: Double = ${dbl(g['overhang-list'])}`);
L.push(`    const val FIELD_STEP_SMALL: Double = ${dbl(g['field-step'].small)}`);
L.push(`    const val FIELD_STEP_LARGE: Double = ${dbl(g['field-step'].large)}`);
L.push('}');
L.push('');

// profiles
L.push('/** The colour a body is filled with by default, by its profile. */');
L.push('internal enum class MutantFill { Primary, Surface, SurfaceVariant, Phosphor, Magenta }');
L.push('');
L.push('/**');
L.push(' * A type profile as the engine draws it (`static K`, held to `mutant/profile`): [radius] in dp (99 is');
L.push(' * "full", clamped to half the side), [overhang] in dp, [dripShare] the share of drips that let a drop go,');
L.push(' * [outline] the stroke in dp, [marks] flow lines, [mosaic] the edge mosaic, [wobble] the melt,');
L.push(' * [deadPixels] the card\'s corner, [round] corner radii not randomised.');
L.push(' */');
L.push('internal class MutantProfile(');
for (const [n, t] of [['radius', 'Double'], ['overhang', 'Double'], ['dripShare', 'Double'], ['fill', 'MutantFill'], ['outline', 'Double'], ['marks', 'Boolean'], ['mosaic', 'Boolean'], ['wobble', 'Double'], ['deadPixels', 'Boolean'], ['round', 'Boolean']]) L.push(`    val ${n}: ${t},`);
L.push(')');
L.push('');
L.push('/** The thirteen body types and their profiles. */');
L.push('internal enum class MutantBody(');
L.push('    val profile: MutantProfile,');
L.push(') {');
for (const k of PROFILES) {
  const K = G.K[k];
  L.push(`    ${pascal(k)}(`);
  L.push('        MutantProfile(');
  L.push(`            radius = ${dbl(K.r)},`);
  L.push(`            overhang = ${dbl(K.over)},`);
  L.push(`            dripShare = ${dbl(K.cf)},`);
  L.push(`            fill = MutantFill.${FILL[K.fill]},`);
  L.push(`            outline = ${dbl(K.ow ?? 3)},`);
  L.push(`            marks = ${(K.marks ?? 1) === 1},`);
  L.push(`            mosaic = ${(K.edge ?? 1) === 1},`);
  L.push(`            wobble = ${dbl(K.wob ?? 1)},`);
  L.push(`            deadPixels = ${(K.dead ?? 0) === 1},`);
  L.push(`            round = ${(K.round ?? 0) === 1},`);
  L.push('        ),');
  L.push('    ),');
}
L[L.length - 1] = '    ),';
L.push('}');
L.push('');

// motion
L.push('/** Motion (`mutant/motion`), ms; a range as its two ends. */');
L.push('internal object MutantMotion {');
const wrap = (text, width) => {
  const out = [];
  let line = '';
  for (const w of text.split(' ')) {
    if (line && line.length + 1 + w.length > width) { out.push(line); line = w; } else line = line ? `${line} ${w}` : w;
  }
  if (line) out.push(line);
  return out;
};
let firstMotion = true;
for (const [k, v] of Object.entries(T.motion)) {
  const E = [];
  const note = [v.event && `on ${v.event}`, v.curve && `curve: ${v.curve}`].filter(Boolean).join('; ');
  if (Array.isArray(v.ms)) {
    E.push(`    const val ${constName(k)}_MIN_MS: Double = ${dbl(v.ms[0])}`);
    E.push(`    const val ${constName(k)}_MAX_MS: Double = ${dbl(v.ms[1])}`);
  } else if (typeof v.ms === 'number') E.push(`    const val ${constName(k)}_MS: Double = ${dbl(v.ms)}`);
  if (v.every !== undefined) E.push(`    const val ${constName(k)}_EVERY_MS: Double = ${dbl(v.every)}`);
  if (v.recover !== undefined) E.push(`    const val ${constName(k)}_RECOVER_MS: Double = ${dbl(v.recover)}`);
  if (v.gravity !== undefined) E.push(`    const val ${constName(k)}_GRAVITY: Double = ${dbl(v.gravity)}`);
  if (!E.length) continue;
  if (!firstMotion) L.push('');
  firstMotion = false;
  if (note) for (const line of wrap(`${k}: ${note}`, 110)) L.push(`    // ${line}`);
  L.push(...E);
}
L.push('}');
L.push('');

// genome
L.push('/** A gene\'s range and default (`mutant/genome`). */');
L.push('internal class MutantGene(');
L.push('    val min: Double,');
L.push('    val max: Double,');
L.push('    val default: Double?,');
L.push(')');
L.push('');
L.push('/** The genes, by their names in the brief; [MutantGene.default] is null where the tokens give none. */');
L.push('internal object MutantGenome {');
for (const [k, v] of Object.entries(T.genome)) {
  L.push(`    val ${pascal(k)}: MutantGene = MutantGene(${dbl(v.range[0])}, ${dbl(v.range[1])}, ${typeof v.default === 'number' ? dbl(v.default) : 'null'})`);
}
L.push('}');
L.push('');

const text = L.join('\n');
if (problems.length) {
  console.error(`tokens: the design's sources disagree:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch {}
  if (current !== text) { console.error(`${OUT} is stale: run node scripts/tokens.mjs`); process.exit(1); }
  console.log(`tokens: up to date; ${KNOWN.size} known disagreement between the tokens and the engine`);
} else {
  writeFileSync(OUT, text);
  console.log(`tokens: wrote ${OUT}`);
}
